"""Generate the offline studio catalog from the engine and appearance descriptions."""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from zimu_engine import CARD_REGISTRY_BY_ID  # noqa: E402


def build_catalog() -> str:
    descriptions = json.loads((ROOT / "design" / "appearances.json").read_text(encoding="utf-8"))
    names = {card.name for card in CARD_REGISTRY_BY_ID.values()}
    if set(descriptions) != names:
        raise ValueError(f"Appearance descriptions differ from registry: {sorted(set(descriptions) ^ names)}")
    if any(not isinstance(value, str) or not value.strip() for value in descriptions.values()):
        raise ValueError("Every card must have a nonempty appearance description")
    cards = [
        {
            "id": card_id,
            "name": card.name,
            "type": card.card_type.name,
            "rank": card.rank.name if card.rank else None,
            "atk": card.atk,
            "hp": card.hp,
            "cost": card.lp_cost,
            "text": card.text,
            "appearance": descriptions[card.name],
        }
        for card_id, card in CARD_REGISTRY_BY_ID.items()
    ]
    return "// Generated by design/build_catalog.py; do not edit directly.\nwindow.ZIMU_CATALOG = " + json.dumps(cards, ensure_ascii=False, indent=2) + ";\n"


if __name__ == "__main__":
    (ROOT / "design" / "card-catalog.js").write_text(build_catalog(), encoding="utf-8")
